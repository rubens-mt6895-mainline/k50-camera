def load_mode_table(name):
    """Read /root/mode_<name>.txt, as written by scripts/gen_mode_table.py."""
    for path in ("/root/mode_%s.txt" % name,
                 os.path.join(os.path.dirname(os.path.abspath(__file__)),
                              "mode_%s.txt" % name)):
        if not os.path.exists(path):
            continue
        vals = []
        with open(path) as fh:
            for line in fh:
                line = line.split("#")[0].strip()
                if not line:
                    continue
                parts = line.replace(",", " ").split()
                vals += [int(parts[0], 0), int(parts[1], 0)]
        return vals, path
    return None, None


# Optional vendor mode table instead of the built-in preview list, selected with
#   IMX582_MODE=custom3 python3 imx582_bring.py
# The tables live in src/rubensimx582_Sensor.h; scripts/gen_mode_table.py
# extracts one into out/modes/mode_<name>.txt and zz_ctrl_run.sh pushes it to
# /root.  A mode switch is nothing but this replay plus the matching driver
# geometry (exp_hsize/exp_vsize/out_width/out_height, see scripts/zz_mode.sh).
MODE = os.environ.get("IMX582_MODE", "").strip()
if "--mode" in sys.argv:
    MODE = sys.argv[sys.argv.index("--mode") + 1]


def main():
    dump_only = "--dump" in sys.argv
    fd = os.open(BUS, os.O_RDWR)
    fcntl.ioctl(fd, I2C_SLAVE, ADDR)

    def wr(reg, val):
        b = (ctypes.c_uint8 * 3)((reg >> 8) & 0xFF, reg & 0xFF, val & 0xFF)
        m = (i2c_msg * 1)()
        m[0].addr = ADDR; m[0].flags = 0; m[0].len = 3
        m[0].buf = ctypes.cast(b, ctypes.POINTER(ctypes.c_uint8))
        fcntl.ioctl(fd, I2C_RDWR, i2c_rdwr_ioctl_data(m, 1))

    def rd(reg):
        b = (ctypes.c_uint8 * 2)((reg >> 8) & 0xFF, reg & 0xFF)
        r = (ctypes.c_uint8 * 1)()
        m = (i2c_msg * 2)()
        m[0].addr = ADDR; m[0].flags = 0; m[0].len = 2
        m[0].buf = ctypes.cast(b, ctypes.POINTER(ctypes.c_uint8))
        m[1].addr = ADDR; m[1].flags = 1; m[1].len = 1
        m[1].buf = ctypes.cast(r, ctypes.POINTER(ctypes.c_uint8))
        fcntl.ioctl(fd, I2C_RDWR, i2c_rdwr_ioctl_data(m, 2))
        return r[0]

    print("ID 0x0016=0x%02x 0x0017=0x%02x" % (rd(0x0016), rd(0x0017)))
    print("== before ==")
    for r in (0x0100, 0x0101, 0x0112, 0x0114, 0x0307, 0x0340, 0x0341):
        print("  0x%04x = 0x%02x" % (r, rd(r)))
    if dump_only:
        os.close(fd); return

    print("== stream off (0x0100=0x00) ==")
    wr(0x0100, 0x00); time.sleep(0.02)

    print("== init_setting: %d pairs ==" % (len(INIT) // 2))
    t0 = time.time()
    for i in range(0, len(INIT), 2):
        wr(INIT[i], INIT[i + 1])
    print("   %d writes in %.1f ms" % (len(INIT) // 2, (time.time() - t0) * 1000))
    time.sleep(0.02)

    table = PREVIEW
    if MODE:
        table, path = load_mode_table(MODE)
        if table is None:
            print("!! no table for mode %s (expected /root/mode_%s.txt)" % (MODE, MODE))
            os.close(fd)
            return
        print("== mode %s table from %s ==" % (MODE, path))

    print("== mode table: %d pairs ==" % (len(table) // 2))
    t0 = time.time()
    for i in range(0, len(table), 2):
        wr(table[i], table[i + 1])
    print("   %d writes in %.1f ms" % (len(table) // 2, (time.time() - t0) * 1000))
    time.sleep(0.05)

    print("== stream on (0x0100=0x01) ==")
    wr(0x0100, 0x01); time.sleep(0.05)

    print("== after ==")
    for r in (0x0100, 0x0101, 0x0112, 0x0113, 0x0114, 0x0115, 0x0307, 0x030d,
              0x030e, 0x030f, 0x0310, 0x0340, 0x0341, 0x0342, 0x0343):
        print("  0x%04x = 0x%02x" % (r, rd(r)))
    os.close(fd)
    print("== imx582_bring done ==")

main()
