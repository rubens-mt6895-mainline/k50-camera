#!/bin/sh
# zz_regs.sh - read-only IMX582 mode registers (what the sensor is really doing).
# Safe while cam_cap owns the sensor: this only reads.
echo "=== IMX582 registers now ==="
for pair in "0x01 0x00:0x0100" "0x01 0x12:0x0112" "0x01 0x14:0x0114" \
            "0x03 0x05:0x0305" "0x03 0x06:0x0306" "0x03 0x07:0x0307" \
            "0x09 0x00:0x0900" "0x09 0x01:0x0901" "0x09 0x02:0x0902" \
            "0x03 0x40:0x0340" "0x03 0x41:0x0341" "0x03 0x42:0x0342" "0x03 0x43:0x0343" \
            "0x03 0x4C:0x034C" "0x03 0x4D:0x034D" "0x03 0x4E:0x034E" "0x03 0x4F:0x034F" \
            "0x04 0x08:0x0408" "0x04 0x09:0x0409" "0x04 0x0C:0x040C" "0x04 0x0D:0x040D" \
            "0x04 0x0E:0x040E" "0x04 0x0F:0x040F" "0x03 0x0E:0x030E" "0x03 0x0F:0x030F"; do
	a="${pair%%:*}"; r="${pair##*:}"
	echo "  $r = $(i2ctransfer -f -y 10 w2@0x10 $a r1 2>&1)"
done
echo "=== driver view ==="
grep -E '^(source|avg|stats|ae)' /proc/camcap_info 2>/dev/null
echo "=== zz_regs done ==="
