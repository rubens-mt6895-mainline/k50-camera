#!/bin/sh
# zz_v76.sh - IMX582 当前寄存器状态 + SENINF/DPHY 状态复核
echo "=== sensor state dump (i2c-10 @0x10) ==="
r() { i2ctransfer -f -y 10 w2@0x10 "$1" "$2" r1 2>&1; }
echo "  0x0100 = $(r 0x01 0x00)"
echo "  0x0101 = $(r 0x01 0x01)"
echo "  0x0112 = $(r 0x01 0x12)"
echo "  0x0113 = $(r 0x01 0x13)"
echo "  0x0114 = $(r 0x01 0x14)"
echo "  0x0115 = $(r 0x01 0x15)"
echo "  0x0136 = $(r 0x01 0x36)"
echo "  0x0137 = $(r 0x01 0x37)"
echo "  0x0307 = $(r 0x03 0x07)"
echo "  0x030d = $(r 0x03 0x0d)"
echo "  0x030e = $(r 0x03 0x0e)"
echo "  0x030f = $(r 0x03 0x0f)"
echo "  0x0310 = $(r 0x03 0x10)"
echo "  0x0311 = $(r 0x03 0x11)"
echo "  0xa000 = $(r 0xa0 0x00)"
echo "  0xa001 = $(r 0xa0 0x01)"
echo "=== SENINF/DPHY state ==="
for a in 0x1a014200 0x1a014204 0x1a014208 0x1a014210 0x1a014a00 0x1a014a04 0x1a014a08 0x1a014a10 0x1a014adc 0x1a014ae0 0x1a010048 0x11c86000 0x11c86004 0x11c86010 0x11c86020 0x11c86030 0x11c86034 0x11c860f0 0x11c8608c; do
  echo "  $a = $(busybox devmem $a 32 2>&1)"
done
echo "=== end ==="
